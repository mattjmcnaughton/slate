@pytest.mark.parametrize(
    "phrase",
    [
        "blah",
        "every",
        "every blue moon",
        "every second",  # ambiguous without a weekday or unit
        "every 32nd",
        "every 1000 days",  # counts stop at 999
        "every 334 quarters",  # ... also when counted in months
        "every Feb 30",
        "tomorrow blah",
        "Feb 30",
        "2026-02-30",
        "9999-12-31",  # years outside 1970-2199 are not dates
        "1/1/1969",
        "every day starting 9999-12-31",
        "13/1",
        "12/32",
        "25:00",
        "9:75",
        "13pm",
        "0am",
        "in 0 days",
        "next",
        "1984",
        "5",
        "at 5",  # a bare hour needs a date
        "for 6 weeks",  # a bound needs a rule
        "every Mon-Fri",  # ranges are not supported
    ],
)
def test_not_understood(phrase: str) -> None:
    result = parse_schedule(phrase, ctx("sat"))
    assert result.due is None
    assert result.recurrence is None
    assert result.error == f"Could not understand “{phrase}”"


@pytest.mark.parametrize("phrase", ["", "   ", "\n"])
def test_empty(phrase: str) -> None:
    assert parse_schedule(phrase, ctx("sat")).error == "Empty schedule"


def test_a_rule_with_no_dates_is_an_error() -> None:
    result = parse_schedule("every day until yesterday", ctx("sat"))
    assert result.due is None
    assert result.recurrence is None
    assert result.error == "No dates match “every day until yesterday”"
