@pytest.mark.parametrize(("now", "phrase", "day", "at"), ONE_OFFS)
def test_one_off(now: str, phrase: str, day: str, at: str | None) -> None:
    result = parse_schedule(phrase, ctx(now))
    assert result.error is None
    assert result.recurrence is None
    assert result.due is not None
    assert (result.due.date, result.due.time) == (d(day), t(at))


