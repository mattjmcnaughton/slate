@pytest.mark.parametrize(
    ("now", "phrase", "rrule", "mode", "dtstart", "due", "at"), RECURRENCES
)
def test_recurrence(
    now: str,
    phrase: str,
    rrule: str,
    mode: RecurrenceMode,
    dtstart: str,
    due: str,
    at: str | None,
) -> None:
    result = parse_schedule(phrase, ctx(now))
    assert result.error is None
    rec = result.recurrence
    assert rec is not None
    assert result.due is not None
    assert (rec.rrule, rec.mode, rec.dtstart, rec.time) == (
        rrule,
        mode,
        d(dtstart),
        t(at),
    )
    assert (result.due.date, result.due.time) == (d(due), t(at))


@pytest.mark.parametrize(
    ("now", "phrase", "rrule", "mode", "dtstart", "due", "at"), RECURRENCES
)
def test_normalized_text_parses_back_to_the_same_rule(
    now: str,
    phrase: str,
    rrule: str,
    mode: RecurrenceMode,
    dtstart: str,
    due: str,
    at: str | None,
) -> None:
    """``Recurrence.text`` can be shown in an edit field and submitted again."""
    rec = parse_schedule(phrase, ctx(now)).recurrence
    assert rec is not None
    again = parse_schedule(rec.text, ctx(now)).recurrence
    assert again is not None, rec.text
    assert (again.rrule, again.mode, again.time, again.text) == (
        rrule,
        mode,
        t(at),
        rec.text,
    )


